"use client";

import React, { useEffect, useState } from "react";
import { cx } from "../ui/cx";

export type PlateVariant = "vault" | "attack" | "trade" | "ledger";

const SRC: Record<PlateVariant, string> = {
  vault: "/art/plate-vault.svg",
  attack: "/art/plate-attack.svg",
  trade: "/art/plate-trade.svg",
  ledger: "/art/plate-ledger.svg",
};

// Small prints use thicker lines and fewer curves so the weave survives at ~220px.
const SRC_SM: Record<PlateVariant, string> = {
  vault: "/art/plate-vault.svg",
  attack: "/art/plate-attack-sm.svg",
  trade: "/art/plate-trade-sm.svg",
  ledger: "/art/plate-ledger-sm.svg",
};

/**
 * Engraved guilloche plate (original, generated by scripts/generate-art.mjs).
 * Printed on the Blue page in White line work with an Onahau inner rosette.
 */
export function Plate({
  variant = "vault",
  caption,
  animate = true,
  compact = false,
  className,
}: {
  variant?: PlateVariant;
  caption?: [string, string];
  animate?: boolean;
  compact?: boolean;
  className?: string;
}) {
  // Settle-in on mount: a plain transition (no keyframe state to get stuck).
  const [ready, setReady] = useState(!animate);
  useEffect(() => {
    if (!animate) return;
    const id = requestAnimationFrame(() => setReady(true));
    return () => cancelAnimationFrame(id);
  }, [animate]);

  return (
    <figure className={cx("m-0", className)}>
      <div
        className={cx(
          "grain grain-circle relative aspect-square w-full overflow-hidden",
          animate && "transition-[opacity,transform] duration-[1100ms] ease-out",
          !ready && "scale-[0.965] -rotate-[4deg] opacity-0"
        )}
      >
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={(compact ? SRC_SM : SRC)[variant]}
          alt=""
          aria-hidden="true"
          draggable={false}
          decoding="async"
          className="block h-full w-full select-none"
        />
      </div>
      {caption && (
        <figcaption className="type-label mt-3 flex items-center justify-between gap-4 text-text-2">
          <span>{caption[0]}</span>
          <span>{caption[1]}</span>
        </figcaption>
      )}
    </figure>
  );
}

/** Tileable guilloche strip. `blue` for White paper, `white` for the Blue page. */
export function Band({ tone = "white", className }: { tone?: "white" | "blue"; className?: string }) {
  return (
    <div
      role="presentation"
      aria-hidden="true"
      className={cx("band", tone === "blue" ? "band-blue" : "band-white", className)}
    />
  );
}

export default Plate;
